import fs from 'node:fs';
import path from 'node:path';

export function nowIso() {
  return new Date().toISOString();
}

export function toPosix(value) {
  return String(value).replace(/\\/g, '/');
}

export function isSubPath(parent, child) {
  const relative = path.relative(parent, child);
  return relative === '' || (!relative.startsWith('..') && !path.isAbsolute(relative));
}

export function stripBom(text) {
  return text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
}

export function readIfExists(filePath) {
  try {
    return stripBom(fs.readFileSync(filePath, 'utf8'));
  } catch (error) {
    if (error && (error.code === 'ENOENT' || error.code === 'EISDIR')) return null;
    throw error;
  }
}

export function exists(filePath) {
  try {
    fs.accessSync(filePath);
    return true;
  } catch {
    return false;
  }
}

export function ensureDir(dirPath) {
  fs.mkdirSync(dirPath, { recursive: true });
  return dirPath;
}

export function writeFile(filePath, content) {
  ensureDir(path.dirname(filePath));
  fs.writeFileSync(filePath, content, 'utf8');
  return filePath;
}

export function writeIfAbsent(filePath, content) {
  if (exists(filePath)) return false;
  writeFile(filePath, content);
  return true;
}

export function appendFile(filePath, content) {
  ensureDir(path.dirname(filePath));
  fs.appendFileSync(filePath, content, 'utf8');
  return filePath;
}

export function listDir(dirPath) {
  try {
    return fs.readdirSync(dirPath, { withFileTypes: true });
  } catch (error) {
    if (error && error.code === 'ENOENT') return [];
    throw error;
  }
}

export function walkFiles(dirPath, options = {}) {
  const { skip = new Set(['node_modules', '.git', 'dist']) } = options;
  const out = [];
  for (const entry of listDir(dirPath)) {
    if (skip.has(entry.name)) continue;
    const full = path.join(dirPath, entry.name);
    if (entry.isDirectory()) {
      out.push(...walkFiles(full, options));
    } else if (entry.isFile()) {
      out.push(full);
    }
  }
  return out;
}

function stripQuotes(value) {
  const trimmed = String(value).trim();
  if (
    (trimmed.startsWith('"') && trimmed.endsWith('"')) ||
    (trimmed.startsWith("'") && trimmed.endsWith("'"))
  ) {
    return trimmed.slice(1, -1);
  }
  return trimmed;
}

/**
 * Parse the small YAML subset used by SpecGate config files: top-level
 * `key: value` pairs, comments, booleans, numbers, null and quoted strings.
 * Nested mappings are intentionally not interpreted.
 */
export function parseSimpleYaml(text) {
  const out = {};
  for (const rawLine of String(text || '').split(/\r?\n/)) {
    const line = rawLine.trimEnd();
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    if (/^\s/.test(rawLine)) continue;
    const match = line.match(/^([A-Za-z0-9_.-]+):\s*(.*)$/);
    if (!match) continue;
    const key = match[1];
    let value = match[2].trim();
    if (value === '' || value === 'null' || value === '~') {
      out[key] = null;
    } else if (value === 'true') {
      out[key] = true;
    } else if (value === 'false') {
      out[key] = false;
    } else if (/^-?\d+$/.test(value)) {
      out[key] = Number(value);
    } else {
      out[key] = stripQuotes(value);
    }
  }
  return out;
}

export function parseFrontmatter(text) {
  const source = stripBom(String(text || ''));
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { data: {}, body: source };
  return {
    data: parseSimpleYaml(match[1]),
    body: source.slice(match[0].length),
  };
}

export function renderConfig(config) {
  const keys = [
    'version',
    'enabled',
    'enforcement',
    'paradigm',
    'language',
    'git',
    'minimal',
    'maxConcurrency',
    'materializeSkills',
    'materializeAgents',
  ];
  const lines = [
    '# SpecGate for DSH project configuration',
    '# Generated by dsh-plugin-specgate. Safe to edit; unknown keys are preserved by the plugin.',
  ];
  for (const key of keys) {
    if (!(key in config)) continue;
    const value = config[key];
    if (value === null || value === undefined) {
      lines.push(`${key}: null`);
    } else if (typeof value === 'string') {
      lines.push(`${key}: ${JSON.stringify(value)}`);
    } else {
      lines.push(`${key}: ${String(value)}`);
    }
  }
  return `${lines.join('\n')}\n`;
}

export function readJsonIfExists(filePath) {
  const text = readIfExists(filePath);
  if (text === null) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

export function writeJson(filePath, value) {
  return writeFile(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

export function countLines(filePath) {
  const text = readIfExists(filePath);
  if (!text) return 0;
  return text.split(/\r?\n/).filter((line) => line.trim()).length;
}

export function unique(values) {
  return [...new Set(values)];
}
