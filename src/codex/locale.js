export function renderChineseData(value, depth = 0) {
  if (value === undefined || value === null) return '无';
  if (typeof value === 'boolean') return value ? '是' : '否';
  if (typeof value !== 'object') return values[value] || String(value);
  if (Array.isArray(value))
    return value.length
      ? value
          .map((entry) => '  '.repeat(depth) + '- ' + renderChineseData(entry, depth + 1))
          .join('\n')
      : '无';
  return Object.entries(value)
    .map(
      ([key, entry]) =>
        '  '.repeat(depth) + (labels[key] || key) + '：' + renderChineseData(entry, depth + 1),
    )
    .join('\n');
}

