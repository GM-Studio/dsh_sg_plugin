export function applyJavaPreset(files, preset) {
  if (!preset || !preset.id) throw new Error('Missing Java preset');
  const out = { ...files };
  const pom = out['backend/pom.xml'];
  if (typeof pom !== 'string') throw new Error('Template is missing backend/pom.xml');
  out['backend/pom.xml'] = pom
    .replace('<version>2.7.18</version>', '<version>' + preset.bootVersion + '</version>')
    .replace(
      '<java.version>1.8</java.version>',
      '<java.version>' + preset.javaVersion + '</java.version>',
    )
    .replace('<version>2.30.0</version>', '<version>' + preset.spotless + '</version>')
    .replace('<version>1.7</version>', '<version>' + preset.gjf + '</version>')
    .replace('<version>9.3</version>', '<version>' + preset.checkstyle + '</version>')
    .replace('<version>2.1.214</version>', '<version>' + preset.h2 + '</version>');
  if (preset.jdk !== '8') {
    for (const key of Object.keys(out)) {
      if (!key.endsWith('.java')) continue;
      out[key] = out[key]
        .replaceAll('javax.persistence', 'jakarta.persistence')
        .replaceAll('javax.validation', 'jakarta.validation')
        .replaceAll('javax.servlet', 'jakarta.servlet')
        .replace(
          /(?:^import (?!static ).+;\n)+/gm,
          (block) => block.trimEnd().split('\n').sort().join('\n') + '\n',
        );
    }
    // Google Java Format sorts jakarta.* before java.*; the base template was Java 8 order.
    const controller = 'backend/src/main/java/com/example/tasks/TaskController.java';
    if (typeof out[controller] === 'string') {
      out[controller] = out[controller].replace(
        'import java.net.URI;\nimport java.util.List;\nimport jakarta.validation.Valid;',
        'import jakarta.validation.Valid;\nimport java.net.URI;\nimport java.util.List;',
      );
    }
    if (String(preset.bootVersion).startsWith('4')) {
      for (const name of Object.keys(out).filter((name) => name.endsWith('.java'))) {
        out[name] = out[name].replaceAll(
          'org.springframework.boot.web.servlet.error.ErrorController',
          'org.springframework.boot.webmvc.error.ErrorController',
        );
      }
      out['backend/pom.xml'] = out['backend/pom.xml'].replace(
        '    <dependency><groupId>org.springframework.boot</groupId><artifactId>spring-boot-starter-test</artifactId><scope>test</scope></dependency>',
        '    <dependency><groupId>org.springframework.boot</groupId><artifactId>spring-boot-starter-test</artifactId><scope>test</scope></dependency>\n' +
          '    <dependency><groupId>org.springframework.boot</groupId><artifactId>spring-boot-starter-webmvc-test</artifactId><scope>test</scope></dependency>',
      );
      for (const testFile of Object.keys(out).filter(
        (name) => name.startsWith('backend/src/test/') && name.endsWith('.java'),
      )) {
        let test = out[testFile];
        test = test
          .replace('import com.fasterxml.jackson.databind.ObjectMapper;\n', '')
          .replace(
            'import org.springframework.test.web.servlet.MockMvc;',
            'import org.springframework.test.web.servlet.MockMvc;\nimport tools.jackson.databind.ObjectMapper;',
          )
          .replace(
            'import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;\n',
            '',
          )
          .replace(
            'import org.springframework.boot.test.context.SpringBootTest;',
            'import org.springframework.boot.test.context.SpringBootTest;\nimport org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;',
          );
        out[testFile] = test;
      }
    }
  }
  out['.java-version'] = preset.jdk + '\n';
  out['README.md'] = readmeFor(out['README.md'], preset);
  out['docs/security.md'] = securityFor(out['docs/security.md'], preset);
  return out;
}

export function templateHash(files) {
  if (typeof files?.__specgateCanonicalTemplateHash === 'string')
    return files.__specgateCanonicalTemplateHash;
  const digest = createHash('sha256');
  for (const key of Object.keys(files).sort()) {
    digest.update(key);
    digest.update('\0');
    digest.update(String(files[key]));
    digest.update('\0');
  }
  return digest.digest('hex');
}

export const PLATFORM_RESULTS = ['passed', 'failed', 'not-run'];

/**
 * True only when a run carries evidence produced by a real verification:
 * a parseable `verifiedAt` timestamp plus the `validateVerificationEvidence`
 * result (ok + real runId + 64-hex sourceHash). Anything weaker is a fabrication.
 */
function hasRealPlatformEvidence(verifiedAt, evidence) {
  if (typeof verifiedAt !== 'string' || !Number.isFinite(Date.parse(verifiedAt))) return false;
  if (!evidence || typeof evidence !== 'object' || evidence.ok !== true) return false;
  if (typeof evidence.runId !== 'string' || !/^[\w-]+$/.test(evidence.runId)) return false;
  if (typeof evidence.sourceHash !== 'string' || !/^[a-f\d]{64}$/.test(evidence.sourceHash))
    return false;
  return true;
}

/**
 * Pure helper shared by the matrix runner and tests: turn one real verification
 * run into the platform-scoped manifest update for a preset.
 *
 * Returns `{ platform, record }` where `record` is the next value for
 * `GOLDEN_MANIFEST.presets[<id>].platforms[<platform>]`. It never mutates the
 * manifest, and it refuses to record a `passed` platform unless the run carries
 * real evidence, so a pass can never be fabricated.
 *
 * `run` = { platform?, result, verifiedAt?, evidence?, toolchain?, commands?, reason? }
 * `result` must be one of `PLATFORM_RESULTS`; only `passed` requires evidence.
 */
export function platformVerificationRecord(preset, run = {}) {
  const id = typeof preset === 'string' ? preset : preset?.id;
  if (!JAVA_PRESETS.some((item) => item.id === id))
    throw new Error('Unknown Java preset for golden record: ' + id);
  const frontend = run.frontend || 'vue';
  if (!['vue', 'react'].includes(frontend))
    throw new Error('Unknown frontend for golden record: ' + frontend);
  const required = GOLDEN_MANIFEST.requiredPlatforms || [];
  const platform = run.platform || process.platform;
  if (!required.includes(platform))
    throw new Error(
      'Platform ' + platform + ' is not a required golden platform: ' + required.join(', '),
    );
  const result = run.result;
  if (!PLATFORM_RESULTS.includes(result))
    throw new Error('Unknown platform verification result: ' + result);
  if (result === 'passed' && !hasRealPlatformEvidence(run.verifiedAt, run.evidence))
    throw new Error(
      'Refusing to record a passed platform without real verification evidence (verifiedAt + validated runId/sourceHash)',
    );
  return {
    platform,
    frontend,
    record: {
      result,
      verifiedAt: run.verifiedAt || null,
      evidence: run.evidence || null,
    },
  };
}

export function goldenStatus(preset, hash, frontend = 'vue') {
  const entry = GOLDEN_MANIFEST.presets[preset.id];
  const record = frontend === 'vue' ? entry : (entry?.frontends?.[frontend] ?? null);
  if (!entry || !record) {
    return {
      verified: false,
      frontend,
      reason:
        frontend === 'vue'
          ? '该版本档尚未登记发版验收记录；先执行 /sg-verify 或完成发版前本地验收'
          : '前端 ' + frontend + ' 尚未登记验收记录；先完成真实构建与双平台验收',
      record: null,
    };
  }
  if (record.templateHash !== hash) {
    return {
      verified: false,
      reason: '模板内容与验收记录不一致（模板已变化，需要重新验收）',
      record,
    };
  }
  const requiredPlatforms = GOLDEN_MANIFEST.requiredPlatforms || [];
  const pendingPlatforms = requiredPlatforms.filter(
    (platform) => record.platforms?.[platform]?.result !== 'passed',
  );
  const matrixComplete = pendingPlatforms.length === 0;
  if (record.result !== 'passed')
    return {
      verified: false,
      reason: '模板验收记录未通过',
      record,
      matrixComplete,
      pendingPlatforms,
    };
  if (!matrixComplete) {
    const passedPlatforms = requiredPlatforms.filter(
      (platform) => !pendingPlatforms.includes(platform),
    );
    const reason =
      passedPlatforms.length === 1
        ? '仅 ' +
          passedPlatforms[0] +
          ' 平台通过验收，仍待 ' +
          pendingPlatforms.join('、') +
          ' 平台验收；双平台全部通过前不能标记为已验证'
        : '双平台验收未完成，仍待 ' + pendingPlatforms.join('、') + ' 平台验收';
    return { verified: false, reason, record, matrixComplete, pendingPlatforms };
  }
  return { verified: true, reason: null, record, matrixComplete, pendingPlatforms };
}

